#!/usr/bin/env node
/**
 * Emit the four directions' token CSS for the `/library` route (B1).
 *
 *   pnpm --filter @pipeline/orchestrator exec tsx scripts/build-library-css.mjs
 *
 * `renderSpecTokens` produces a *source* stylesheet: it opens with
 * `@import "tailwindcss"` and declares `@theme inline`, both of which need
 * Tailwind's build step. The library serves its previews from the template's
 * own already-built CSS and overrides only what a direction changes, so this
 * strips those two blocks and keeps the part that is plain CSS — the custom
 * properties and the eight type classes.
 *
 * Committed output, regenerated by hand, because the library is reviewed by
 * the operator and a file that changes under them mid-review is worse than a
 * file that is slightly stale.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { DIRECTIONS, DIRECTION_IDS } from "../src/design/directions/index.js";
import { FACES, FACE_BY_FAMILY } from "../src/design/faces.js";
import { renderSpecTokens } from "../src/design/spec-tokens.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "../../..");
const OUT = join(ROOT, "apps/library/src/app/directions.generated.ts");
const FACES_OUT = join(ROOT, "apps/library/src/app/faces.generated.ts");

/** The midpoint of every range — what the §6.3 sampler will produce. */
function specFor(id) {
  const d = DIRECTIONS[id];
  const mid = ([a, b]) => Math.round(((a + b) / 2) * 1000) / 1000;
  const pair = d.type.pairs[0];
  return {
    version: 2,
    direction: d.id,
    seed: `${d.id}-library`,
    type: {
      display: pair.display,
      body: pair.body,
      ...(d.type.mono[0] === undefined ? {} : { mono: d.type.mono[0] }),
      displayWeight: d.type.displayWeights[0],
      displayTracking: mid(d.type.displayTracking),
      scaleRatio: mid(d.type.scaleRatio),
      displayCase: d.type.displayCase[0],
    },
    color: {
      mode: d.color.modes[0],
      strategy: d.color.strategies[0],
      brandH: 318,
      brandC: Math.min(d.color.maxChroma, 0.08),
    },
    shape: {
      radius: d.shape.radius[0],
      rules: d.shape.rules[0],
      imageFrame: d.shape.imageFrame[0],
    },
    grid: { alignment: d.grid.alignment[0], density: d.grid.density[0] },
    motion: {
      profile: d.motion.profiles[0],
      signatures: [...d.motion.required],
      heroEntrance: d.motion.heroEntrance,
      smoothScroll: d.motion.smoothScroll,
    },
    sections: [
      { type: "hero", archetype: "photo-full" },
      { type: "services", archetype: "list-rule" },
      { type: "contact", archetype: "split-form" },
    ],
    signature: { sectionIndex: 0, concept: "library" },
    rejected: [],
  };
}

const camel = (slug) => slug.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

/** Drop `@import` and the `@theme inline { ... }` block; keep the rest. */
function injectable(css) {
  return css
    .replace(/@import\s+"[^"]+";\s*/g, "")
    .replace(/@theme inline \{[\s\S]*?\n\}\n/, "")
    .trim();
}

/**
 * Point the template's face variables at this direction's actual faces.
 *
 * Without this every preview renders whatever `fonts.ts` loaded, so the
 * library shows four directions in one typeface — which is what it did until
 * now, and what made a `/library` review unable to judge type at all.
 */
function faceVars(spec) {
  const slug = (family) => FACE_BY_FAMILY.get(family)?.slug;
  const lines = [
    `  --font-display-face: var(--face-${slug(spec.type.display)});`,
    `  --font-body-face: var(--face-${slug(spec.type.body)});`,
  ];
  if (spec.type.mono !== undefined) {
    lines.push(`  --font-mono-face: var(--face-${slug(spec.type.mono)});`);
  }
  return `:root {\n${lines.join("\n")}\n}`;
}

const entries = DIRECTION_IDS.map((id) => {
  const spec = specFor(id);
  const css = `${injectable(renderSpecTokens(spec))}\n\n${faceVars(spec)}`;
  return `  ${JSON.stringify(id)}: ${JSON.stringify(css)},`;
});

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(
  OUT,
  `// Generated by apps/orchestrator/scripts/build-library-css.mjs — do not hand-edit.
// The injectable half of each direction's tokens.css: custom properties and
// the eight type classes, with @import and @theme stripped because the
// library preview inherits Tailwind from the template's own build.
export const DIRECTION_CSS: Record<string, string> = {
${entries.join("\n")}
};

export const LIBRARY_DIRECTIONS = ${JSON.stringify(DIRECTION_IDS)};
`,
);

// Every registry face, each exposing its own CSS variable, so a direction
// can point at any of them without the library knowing which in advance.
const faceDecls = FACES.map(
  (f) => `export const ${camel(f.slug)} = localFont({
  src: [
    { path: "../../../../data/fonts/${f.slug}/${f.slug}-latin.woff2", style: "normal" },
    { path: "../../../../data/fonts/${f.slug}/${f.slug}-latin-ext.woff2", style: "normal" },
  ],
  variable: "--face-${f.slug}",${f.variable ? '\n  weight: "100 900",' : ""}
  display: "swap",
  fallback: ["system-ui", "sans-serif"],
  adjustFontFallback: false,
});`,
).join("\n\n");

writeFileSync(
  FACES_OUT,
  `// Generated by apps/orchestrator/scripts/build-library-css.mjs — do not hand-edit.
// Every face in the registry, so any direction's pairing can be previewed.
// Weights are never pinned: a variable face at one weight cannot do an
// optical-size curve, which is what made all four directions look alike.
import localFont from "next/font/local";

${faceDecls}

export const ALL_FACE_VARIABLES = [
${FACES.map((f) => `  ${camel(f.slug)}.variable,`).join("\n")}
].join(" ");
`,
);

console.log(`wrote ${DIRECTION_IDS.length} directions → ${OUT}`);
console.log(`wrote ${FACES.length} faces → ${FACES_OUT}`);

import type { DesignDna } from "./dna.js";

/**
 * Render the client's `src/lib/fonts.ts`.
 *
 * Written by the orchestrator rather than the model for the same reason the
 * palette is: the type pairing is a decision the design stage already made
 * against the sector and the fingerprint ledger, and a model asked to "pick
 * fonts" reaches for the same two faces every time — which is exactly the
 * typographic sameness D6 exists to prevent.
 *
 * Weights are pinned to the ones actually used. Without `weight`, next/font
 * ships the full variable face for both families (~192 KB) and delays the
 * text LCP (DECISIONS D4).
 */
export function renderFonts(dna: DesignDna): string {
  const { display, body, displayWeight } = dna.typePair;

  return `// Generated by the design stage — do not hand-edit.
// Pairing chosen for this client's sector and checked against the design
// fingerprint ledger (docs/DECISIONS.md D6).
import { ${display}, ${body} } from "next/font/google";

/**
 * The display face. A grotesk needs weight ${displayWeight} and negative
 * tracking to read as display rather than as a UI font — at 400 it reads
 * timid at any size (template/design-rules.md §4).
 *
 * latin-ext is not optional: without it ş/ğ/ı/İ/ç/ö/ü fall back mid-word.
 */
export const displayFont = ${display}({
  variable: "--font-display-face",
  subsets: ["latin", "latin-ext"],
  weight: ["${displayWeight}"],
  display: "swap",
});

export const bodyFont = ${body}({
  variable: "--font-body-face",
  subsets: ["latin", "latin-ext"],
  weight: ["400", "500", "600"],
  display: "swap",
});

/** Both variables, for the <html> className. */
export const fontVariables = \`\${displayFont.variable} \${bodyFont.variable}\`;
`;
}

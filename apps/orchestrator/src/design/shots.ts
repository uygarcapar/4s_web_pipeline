import { spawn } from "node:child_process";
import {
  cpSync,
  existsSync,
  mkdirSync,
  readFileSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from "node:fs";
import { join } from "node:path";
import type { DesignSpec } from "@pipeline/core";

import { planLocalFonts, copyFaces } from "./local-fonts.js";
import { renderSpecTokens } from "./spec-tokens.js";

/**
 * Build a candidate and photograph its two folds (D10 §8.2).
 *
 * The folds are §8.2's: desktop 1350×940 and an iPhone 13. **Folds, not
 * full pages** — the comparison is "do these two sites look alike", and a
 * visitor decides that from what is above the fold. A full-page screenshot
 * would also make the similarity a function of how much the client wrote,
 * so a chatty dentist and a terse one would read as different designs when
 * they are the same design.
 */

/** §8.2's desktop fold. */
export const DESKTOP = { width: 1350, height: 940 } as const;

/** §8.2's mobile fold — iPhone 13. */
export const MOBILE = { width: 390, height: 844, deviceScaleFactor: 3 } as const;

export interface CandidateShots {
  dir: string;
  desktop: string;
  mobile: string;
}

export interface PrerenderOptions {
  repoRoot: string;
  /** Where the candidate's site and screenshots go. */
  outDir: string;
  spec: DesignSpec;
  /** The `SiteConfig` object, from `prerenderConfig`. */
  config: Record<string, unknown>;
  /** `runs/<domain>/crawl/assets`, if the crawl downloaded any. */
  assetsDir?: string | undefined;
  port: number;
  log?: (message: string) => void;
}

/**
 * Copy the template, apply the spec, write the config, build, serve,
 * screenshot, stop.
 *
 * Deliberately a production build rather than `next dev`: the fonts, the
 * image optimiser and the CSS all behave differently in dev, and a
 * similarity measured against a dev render is a similarity between two
 * things neither client will ever see.
 */
export async function shootCandidate(options: PrerenderOptions): Promise<CandidateShots> {
  const { repoRoot, outDir, spec, config, assetsDir, port } = options;
  const log = options.log ?? (() => {});
  const siteDir = join(outDir, "site");

  rmSync(siteDir, { recursive: true, force: true });
  mkdirSync(siteDir, { recursive: true });

  // The template, minus the things a scaffold has no use for.
  //
  // The unit tests go too, and `fixtures/` with them — they are a pair.
  // Dropping only `fixtures/` leaves four `*.test.ts` importing a directory
  // that is no longer there, and `next build` type-checks the whole project,
  // so the candidate fails to build for a reason that has nothing to do
  // with the candidate.
  cpSync(join(repoRoot, "template"), siteDir, {
    recursive: true,
    filter: (src) =>
      !src.includes("node_modules") &&
      !src.includes("/.next") &&
      !src.includes("/tests") &&
      !src.includes("/fixtures") &&
      !src.endsWith(".test.ts") &&
      !src.endsWith(".test.tsx"),
  });

  // `node_modules` is SYMLINKED, not copied. pnpm's tree is a forest of
  // relative links into `.pnpm`, and copying it — even with
  // `verbatimSymlinks` — relocates the links without relocating what they
  // point at, so `next` resolves to a path that does not exist. One link to
  // the template's own tree keeps every relative path valid, and saves
  // copying ~400 MB per candidate.
  symlinkSync(join(repoRoot, "template", "node_modules"), join(siteDir, "node_modules"), "dir");

  // The spec's own stylesheet and font module, exactly as the generate
  // stage stages them — this is the part the comparison is actually about.
  writeFileSync(join(siteDir, "src", "styles", "tokens.css"), renderSpecTokens(spec));
  const fonts = planLocalFonts(spec);
  writeFileSync(join(siteDir, "src", "lib", "fonts.ts"), fonts.module);
  copyFaces(fonts, repoRoot, siteDir);

  if (assetsDir !== undefined && existsSync(assetsDir)) {
    cpSync(assetsDir, join(siteDir, "public", "images", "crawl"), { recursive: true });
  }

  writeFileSync(
    join(siteDir, "site.config.ts"),
    `// Generated by the design stage's pre-render (D10 §8.2) — NOT a site.
//
// The copy here is the client's own crawled text, unedited, and the
// placeholders are deliberately not prose. Nothing in this file has been
// through the generate stage's §9 rules. It exists to be screenshotted.
import type { SiteConfig } from "@/lib/schema";

export const siteConfig: SiteConfig = ${JSON.stringify(config, null, 2)};

export default siteConfig;
`,
  );

  log(`building candidate ${spec.seed}`);
  try {
    return await shootSite({ siteDir, outDir, port, build: true });
  } finally {
    // The scaffold goes; the screenshots stay. A built Next copy is ~200 MB
    // and a run can draw two dozen candidates — left behind, one afternoon
    // of runs fills a disk. The PNGs beside it are what the operator
    // reviews and what §8.3 calibrates against, and they are ~1 MB.
    rmSync(siteDir, { recursive: true, force: true });
  }
}

/**
 * Build (optionally) and photograph a site that already exists on disk.
 *
 * Used for the shipped site after verify (§8.2's second vector), where the
 * site is the generate stage's output rather than a scaffold — and where
 * `.next` is usually already built by the verify gates, so `build` is off.
 */
export async function shootSite(options: {
  siteDir: string;
  outDir: string;
  port: number;
  build?: boolean;
}): Promise<CandidateShots> {
  const { siteDir, outDir, port } = options;
  if (options.build !== false && !existsSync(join(siteDir, ".next", "BUILD_ID"))) {
    await run("pnpm", ["exec", "next", "build"], siteDir);
  }

  const server = spawn("pnpm", ["exec", "next", "start", "-p", String(port)], {
    cwd: siteDir,
    stdio: "ignore",
    detached: false,
  });

  try {
    const url = `http://127.0.0.1:${port}/`;
    await waitForServer(url);
    return await screenshot(url, outDir);
  } finally {
    server.kill("SIGTERM");
  }
}

async function screenshot(url: string, outDir: string): Promise<CandidateShots> {
  // `playwright`, not `@playwright/test`: the test runner is the template's
  // dependency and the orchestrator only has the driver. Getting this
  // backwards is what stopped the verify geometry gate from ever running.
  //
  // Imported here rather than at module scope because the CLI loads every
  // stage to print `--help`, and its own test measures that startup against
  // a 5 s budget.
  const { chromium, devices } = await import("playwright");
  const browser = await chromium.launch();
  mkdirSync(outDir, { recursive: true });
  const desktop = join(outDir, "desktop.png");
  const mobile = join(outDir, "mobile.png");

  try {
    const desktopPage = await browser.newPage({ viewport: DESKTOP });
    await desktopPage.goto(url, { waitUntil: "networkidle" });
    await settle(desktopPage);
    await desktopPage.screenshot({ path: desktop });
    await desktopPage.close();

    const mobileContext = await browser.newContext(devices["iPhone 13"]);
    const mobilePage = await mobileContext.newPage();
    await mobilePage.goto(url, { waitUntil: "networkidle" });
    await settle(mobilePage);
    await mobilePage.screenshot({ path: mobile });
    await mobileContext.close();
  } finally {
    await browser.close();
  }

  return { dir: outDir, desktop, mobile };
}

/**
 * Let the entrance animation finish before photographing.
 *
 * Several directions run a hero entrance, and a screenshot taken mid-fade
 * measures the opacity the animation happened to be at — which would make
 * the same candidate embed differently on two runs and turn a deterministic
 * gate into a coin flip. Reduced motion is forced on for the same reason:
 * it is the one state the animation is guaranteed to have finished in.
 */
async function settle(page: {
  emulateMedia: (opts: { reducedMotion: "reduce" }) => Promise<void>;
  waitForTimeout: (ms: number) => Promise<void>;
  evaluate: (fn: () => unknown) => Promise<unknown>;
}): Promise<void> {
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.evaluate(() => document.fonts.ready);
  await page.waitForTimeout(400);
}

function run(command: string, args: string[], cwd: string): Promise<void> {
  return new Promise((resolve, reject) => {
    const child = spawn(command, args, { cwd, stdio: "pipe" });
    let stderr = "";
    child.stderr?.on("data", (chunk: Buffer) => {
      stderr += chunk.toString();
    });
    child.on("error", reject);
    child.on("close", (code) => {
      if (code === 0) resolve();
      else reject(new Error(`${command} ${args.join(" ")} exited ${code}\n${stderr.slice(-2000)}`));
    });
  });
}

/** How long to wait for `next start` before calling the build broken. */
const SERVER_TIMEOUT_MS = 30_000;

async function waitForServer(url: string): Promise<void> {
  const deadline = Date.now() + SERVER_TIMEOUT_MS;
  for (;;) {
    try {
      const response = await fetch(url);
      if (response.ok) return;
    } catch {
      // Not up yet.
    }
    if (Date.now() > deadline) {
      throw new Error(`server did not start within ${SERVER_TIMEOUT_MS}ms: ${url}`);
    }
    await new Promise((r) => setTimeout(r, 250));
  }
}

/** Read a screenshot back, for the embedder. */
export function readShot(path: string): Buffer {
  return readFileSync(path);
}

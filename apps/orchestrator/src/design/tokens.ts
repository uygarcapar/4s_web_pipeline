import type { DesignDna } from "./dna.js";

/**
 * Render the DNA as the generated site's `src/styles/tokens.css`.
 *
 * The type scale is fixed by design-rules.md §4 and is NOT a per-site
 * decision: it is the quality floor that took several review rounds to get
 * right (display/body ≈ 6:1, uppercase tracking ≤ 0.08em, a column-safe
 * heading step). What varies per site is the palette, the faces, and the
 * density rhythm.
 */
export function renderTokens(dna: DesignDna): string {
  const { palette: p, typePair, density } = dna;
  const rhythm = SECTION_RHYTHM[density];

  return `/* Generated by the design stage — do not hand-edit.
   Palette derived from this client's own photographs (${p.name}, hue ${p.hue}).
   Type scale is the shared quality floor: see template/design-rules.md §4. */

@import "tailwindcss";

:root {
  /* One hue family, start to finish (design-rules.md §5). The papers are warm
     and the darks are the same warmth pushed to near-black with a trace of
     this client's own colour, so their photographs sit inside the palette
     instead of fighting it. The photographs are the only chroma. */
  --paper-50: ${p.paper[50]};
  --paper-100: ${p.paper[100]};
  --paper-200: ${p.paper[200]};
  --paper-300: ${p.paper[300]};
  --paper-400: ${p.paper[400]};
  --paper-500: ${p.paper[500]};

  --ink-900: ${p.ink[900]};
  --ink-800: ${p.ink[800]};
  --ink-700: ${p.ink[700]};
  --ink-600: ${p.ink[600]};
  --ink-400: ${p.ink[400]};

  /* hover and focus only — never a surface */
  --accent: ${p.accent};

  --background: var(--paper-100);
  --foreground: var(--ink-900);

  --font-display: var(--font-display-face);
  --font-sans: var(--font-body-face);

  /* vertical rhythm, from this client's content volume (${density}) */
  --section-y: ${rhythm.sectionY};
  --section-y-lg: ${rhythm.sectionYLg};
}

@theme inline {
  --color-background: var(--background);
  --color-foreground: var(--foreground);
  --color-paper-50: var(--paper-50);
  --color-paper-100: var(--paper-100);
  --color-paper-200: var(--paper-200);
  --color-paper-300: var(--paper-300);
  --color-paper-400: var(--paper-400);
  --color-paper-500: var(--paper-500);
  --color-ink-900: var(--ink-900);
  --color-ink-800: var(--ink-800);
  --color-ink-700: var(--ink-700);
  --color-ink-600: var(--ink-600);
  --color-ink-400: var(--ink-400);
  --color-accent: var(--accent);
  --font-display: var(--font-display);
  --font-sans: var(--font-sans);
}

html {
  scrollbar-width: thin;
  scrollbar-color: var(--paper-400) transparent;
}

body {
  background: var(--background);
  color: var(--foreground);
  font-family: var(--font-sans), system-ui, sans-serif;
  overflow-x: hidden;
}

::selection {
  background: var(--ink-900);
  color: var(--paper-100);
}

/* ---- type scale (design-rules.md §4) -------------------------------------
   Display/body ≈ 6:1. Big type only reads as big against a quiet floor;
   raising the supporting sizes to meet the headline flattens the page even
   though every size got bigger. */

/* The vmin term keeps a three-line display block inside a short laptop
   viewport; the rem floor takes over on a tall phone. */
.t-display {
  font-family: var(--font-display), system-ui, sans-serif;
  font-size: clamp(3.25rem, min(10.5vw, 17.5vmin), 11.5rem);
  font-weight: ${typePair.displayWeight};
  line-height: 0.86;
  letter-spacing: -0.05em;
  overflow-wrap: break-word;
}

/* Full-width headings only — the container caps while vw keeps growing. */
.t-h2 {
  font-family: var(--font-display), system-ui, sans-serif;
  font-size: clamp(2.5rem, 8vw, 7rem);
  font-weight: ${typePair.displayWeight};
  line-height: 0.9;
  letter-spacing: -0.045em;
  overflow-wrap: break-word;
}

/* The same heading when it shares a row with another column. Capped in rem
   because the column stops growing at ~540px while the viewport does not: a
   single long Turkish word at 7rem has no break opportunity and lands on top
   of whatever sits beside it. */
.t-h2-col {
  font-family: var(--font-display), system-ui, sans-serif;
  font-size: clamp(1.875rem, 4vw, 4rem);
  font-weight: ${typePair.displayWeight};
  line-height: 0.95;
  letter-spacing: -0.04em;
  overflow-wrap: break-word;
}

.t-h3 {
  font-family: var(--font-display), system-ui, sans-serif;
  font-size: clamp(1.75rem, 3.2vw, 2.75rem);
  font-weight: 700;
  line-height: 1.04;
  letter-spacing: -0.035em;
  overflow-wrap: break-word;
}

.t-lead {
  font-size: clamp(1rem, 1.15vw, 1.0625rem);
  line-height: 1.5;
  letter-spacing: -0.005em;
}

.t-body {
  font-size: clamp(0.9375rem, 1vw, 1rem);
  line-height: 1.62;
}

/* Size and case only — no colour. This rule is emitted after Tailwind's
   utilities and would silently beat every text-* written beside it, landing
   one grey on dark grounds and on photographs alike. */
.meta {
  font-size: clamp(0.625rem, 0.8vw, 0.75rem);
  font-weight: 400;
  letter-spacing: 0.07em;
  text-transform: uppercase;
}

.btn-label {
  font-size: 0.8125rem;
  font-weight: 600;
  letter-spacing: 0.07em;
  text-transform: uppercase;
  white-space: nowrap;
}

/* The fixed bar must not cover the heading an in-page jump lands on. */
:target,
[id] {
  scroll-margin-top: 5rem;
}

/* Each display line is a mask; its inner span is what GSAP moves. Turkish
   descenders and cedillas sit low — without this padding the mask cuts the
   tail off ş and the dot off İ, which silently renames the business. */
.line-mask {
  display: block;
  overflow: hidden;
  padding-bottom: 0.16em;
  margin-bottom: -0.16em;
}
`;
}

/**
 * Section padding by density. A business with 400 content blocks wants a
 * tighter rhythm than one with 40, or the sparse site reads as empty and the
 * dense one as relentless (design-rules.md §10.2).
 */
const SECTION_RHYTHM: Record<DesignDna["density"], { sectionY: string; sectionYLg: string }> = {
  poster: { sectionY: "7rem", sectionYLg: "11rem" },
  standard: { sectionY: "6rem", sectionYLg: "9rem" },
  editorial: { sectionY: "5rem", sectionYLg: "7.5rem" },
};

import { readFileSync } from "node:fs";
import { connection } from "next/server";
import { join } from "node:path";

import { CalibrateClient, type CalibrationPair } from "./client";

/**
 * The §8.3 labelling surface.
 *
 * Shows pairs of pre-rendered candidates side by side and asks one
 * question: do these two look like the same site? The answer sets the five
 * thresholds that currently hold D10's diversity guarantee up on starting
 * values nobody measured.
 *
 * **No numbers are shown.** The structural distance and the cosine
 * similarity are both in `pairs.json` and neither reaches this page — a
 * visible 0.41 would anchor the judgement it is supposed to be measuring,
 * and the whole exercise is worth nothing if the labels agree with the
 * detector because the labeller could see what the detector said.
 */
/**
 * Blocking, not streamed.
 *
 * `pairs.json` is regenerated by a script, so this page is read at request
 * time rather than baked at build. Under `cacheComponents` that needs
 * either a Suspense boundary or this — and a fallback would be pure
 * ceremony for a local file read that takes under a millisecond.
 */
export const instant = false;

interface PairsFile {
  generatedFrom: { directions: string[]; candidates: number; pairsConsidered: number };
  pairs: CalibrationPair[];
}

export default async function CalibratePage() {
  await connection();

  const path = join(process.cwd(), "..", "..", "data", "calibration", "pairs.json");

  let file: PairsFile | null = null;
  try {
    file = JSON.parse(readFileSync(path, "utf8")) as PairsFile;
  } catch {
    file = null;
  }

  if (file === null) {
    return (
      <main className="mx-auto max-w-2xl px-6 py-24">
        <h1 className="text-2xl font-semibold">No pairs yet</h1>
        <p className="mt-4 text-sm leading-relaxed opacity-80">
          Generate them first — it renders every direction, screenshots both
          folds and embeds them, which takes a few minutes:
        </p>
        <pre className="mt-4 overflow-x-auto rounded bg-black/5 p-4 text-xs">
          pnpm --filter @pipeline/orchestrator calibrate
        </pre>
      </main>
    );
  }

  return (
    <CalibrateClient
      pairs={file.pairs}
      summary={`${file.generatedFrom.candidates} candidates from ${file.generatedFrom.directions.length} directions · ${file.pairs.length} of ${file.generatedFrom.pairsConsidered} pairs sampled`}
    />
  );
}
